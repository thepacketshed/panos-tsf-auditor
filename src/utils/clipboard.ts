/**
 * Copies text to the clipboard.
 *
 * navigator.clipboard.writeText is rejected when the app runs inside an
 * iframe without the clipboard-write permission (e.g. embedded in WordPress),
 * and is missing on non-secure origins. In those cases fall back to a hidden
 * textarea + document.execCommand('copy'), which still works from a click.
 *
 * Returns true if the copy succeeded.
 */
export async function copyText(text: string): Promise<boolean> {
  if (navigator.clipboard && window.isSecureContext) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // fall through to legacy method
    }
  }

  try {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.setAttribute('readonly', '');
    ta.style.position = 'fixed';
    ta.style.top = '0';
    ta.style.left = '0';
    ta.style.width = '1px';
    ta.style.height = '1px';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.focus();
    ta.select();
    ta.setSelectionRange(0, text.length);
    const ok = document.execCommand('copy');
    ta.remove();
    return ok;
  } catch {
    return false;
  }
}
